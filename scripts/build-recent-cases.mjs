const records = [];
for (const [name, year, period, category, region, title, text, id, needle] of entries) {
  const source = manifest.find((r) => r.id === id);
  if (!source) throw Error('Missing source ' + id);
  const content = (await readFile(root + id + '.txt', 'utf8')).split('中央统战部')[0];
  const at = content.indexOf(needle);
  if (at < 0) throw Error('Missing evidence ' + needle);
  records.push({
    name,
    year,
    period,
    category,
    region,
    title,
    text,
    updatedAt: '2026-10-10',
    sources: [
      {
        url: source.url,
        publisher: '国家民族事务委员会 · 地方报道',
        snapshot: source.snapshot,
        sha256: source.sha256,
        evidence: needle,
        reportedAt: content.match(/日期：(\d{4}-\d{2}-\d{2})/)?.[1],
      },
    ],
  });
}
await writeFile('src/data/recent-cases.json', JSON.stringify(records, null, 2) + '\n');
console.log('Built', records.length, 'dated recent cases');
